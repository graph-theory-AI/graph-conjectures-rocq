(** * Maximum independent sets in graphs without long induced paths

Groenland, Okrasa, Rzążewski, Scott, Seymour, Spirkl, "H-colouring P_t-free graphs in
subexponential time", Discrete Applied Mathematics 267 (2019), arXiv:1803.05396, open problem
(1803.05396__01).

Let P_t be the path on t vertices.  A graph is P_t-free if it has no induced subgraph isomorphic
to P_t.

Problem: determine whether the maximum independent set problem can be solved in polynomial time
for P_t-free graphs, for t >= 7.

The proposition states the positive answer, for every t >= 7.

Encoding.  Polynomial-time algorithms are programs of the small language defined below, with a
polynomial number of steps.  The program receives the adjacency matrix of a graph G, and returns
the maximum size of an independent set if G is P_t-free.  The number of steps is bounded for all
graphs, which is equivalent, as a program can be stopped after a given number of steps. *)

From GraphTheory Require Import preliminaries digraph sgraph.
From GraphTheory Require dom.
From mathcomp Require Import boot.

